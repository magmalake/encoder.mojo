"""Generate src/encoder/_unicode.mojo, the Unicode data BertNormalizer and
BertPreTokenizer need, from Python's unicodedata.

    pixi run -e fixtures python -I tools/gen_unicode.py

The tables are packed into string literals and parsed once at load time,
which keeps compile times down compared with large array literals.
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "encoder" / "_unicode.mojo"
MAX_CP = 0x110000
HANGUL = range(0xAC00, 0xD7A4)  # decomposed algorithmically in Mojo


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX_CP):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def cat(cp: int) -> str:
    return unicodedata.category(chr(cp))


def pack_ranges(rs) -> str:
    return ",".join(f"{lo:x}-{hi:x}" for lo, hi in rs)


def pack_map(m: dict[int, list[int]]) -> str:
    return ";".join(
        f"{k:x}:" + " ".join(f"{v:x}" for v in vs) for k, vs in sorted(m.items())
    )


def literal(s: str, width: int = 76) -> str:
    """A parenthesised run of adjacent string literals, `width` chars each."""
    parts = [s[i : i + width] for i in range(0, len(s), width)] or [""]
    return "(\n" + "\n".join(f'    "{p}"' for p in parts) + "\n)"


def main() -> None:
    other = ranges(lambda cp: cat(cp).startswith("C"))
    punct = ranges(lambda cp: cat(cp).startswith("P"))
    mark = ranges(lambda cp: cat(cp) == "Mn")

    decomp: dict[int, list[int]] = {}
    lower: dict[int, list[int]] = {}
    for cp in range(MAX_CP):
        c = chr(cp)
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if cp not in HANGUL:
            d = unicodedata.normalize("NFD", c)
            if d != c:
                decomp[cp] = [ord(x) for x in d]
        lo = c.lower()
        if lo != c:
            lower[cp] = [ord(x) for x in lo]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# Generated by tools/gen_unicode.py from Python's unicodedata "
        f"{unicodedata.unidata_version}.\n"
        "# Do not edit by hand.\n\n"
        "# Ranges of general category C* (control, format, surrogate,\n"
        "# private use, unassigned): what BertNormalizer's clean_text drops.\n"
        f"comptime OTHER_RANGES: StaticString = {literal(pack_ranges(other))}\n\n"
        "# Ranges of general category P*: punctuation BertPreTokenizer\n"
        "# splits off (ASCII punctuation is checked separately).\n"
        f"comptime PUNCT_RANGES: StaticString = {literal(pack_ranges(punct))}\n\n"
        "# Ranges of general category Mn: marks strip_accents removes.\n"
        f"comptime MARK_RANGES: StaticString = {literal(pack_ranges(mark))}\n\n"
        "# Full canonical decomposition (NFD) of each code point that has\n"
        "# one, except Hangul syllables.\n"
        f"comptime DECOMPOSITIONS: StaticString = {literal(pack_map(decomp))}\n\n"
        "# Full lowercase mapping of each code point that has one.\n"
        f"comptime LOWERCASE: StaticString = {literal(pack_map(lower))}\n"
    )
    print(
        f"{OUT.relative_to(ROOT)}: {len(other)} other, {len(punct)} punct, "
        f"{len(mark)} mark ranges; {len(decomp)} decompositions, "
        f"{len(lower)} lowercase; {OUT.stat().st_size // 1024} KB"
    )


if __name__ == "__main__":
    sys.exit(main())
